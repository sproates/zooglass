const gap = (sequence: number, status: string) => ({
  from: sequence,
  through: sequence,
  status,
});
const observed = (
  through: number | null,
  missing: Progress["missing"] = [],
): Progress => ({
  ...absentProgress,
  observed: through,
  floor: through === null ? null : 1,
  missing,
});
export type Market = {
  ref: string | null;
  freshness: string;
  progress: Progress;
};
const market = (
  ref: string | null,
  freshness: string,
  through: number | null,
  watermark: number | null = null,
  missing: Progress["missing"] = [],
): Market => ({
  ref,
  freshness,
  progress: {
    ...observed(through, missing),
    watermark,
    complete: null,
    completeness: watermark === null ? "unknown" : "incomplete",
  },
});
