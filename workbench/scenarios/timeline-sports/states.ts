export function state(row: StateRow, viewId: string): State {
  const index = views.indexOf(viewId),
    [home, away] = sides(
      row.stages[index],
      row.cycle,
      row.entityId,
      viewId === "first-reported",
      row.floors[index],
    );
  const book = row.market.ref ? publications.get(row.market.ref)! : null;
  return {
    entityId: row.entityId,
    version: row.versions[index],
    match: row.match ? publications.get(row.match)!.body : null,
    market: book?.body ?? null,
    marketAt: book?.atMs ?? null,
    marketFreshness: row.market.freshness,
    home,
    away,
    matchProgress: row.progress,
    bookProgress: row.market.progress,
  };
}
