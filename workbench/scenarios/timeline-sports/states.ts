export type StateRow = {
  id: string;
  atMs: number;
  entityId: string;
  cycle: number;
  versions: [number, number, number];
  stages: [FactStage, FactStage, FactStage];
  floors: [number, number, number];
  match: string | null;
  market: Market;
  progress: Progress;
  emitted: string[];
};
const all = views;
function row(
  id: string,
  atMs: number,
  versions: StateRow["versions"],
  stage: FactStage | StateRow["stages"],
  through: number | null,
  book: keyof typeof markets,
  match: string | null = "step-0-0",
  cycle = 1,
  floors: StateRow["floors"] = [1, 1, 1],
  missing: Progress["missing"] = [],
  emitted = all,
): StateRow {
  return {
    id,
    atMs,
    entityId: "match-1",
    cycle,
    versions,
    stages: typeof stage === "string" ? [stage, stage, stage] : stage,
    floors,
    match,
    market: markets[book],
    progress: observed(through, missing),
    emitted,
  };
}
